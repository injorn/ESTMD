// Local additive upgrade with an online SQLite backup and preservation check.
require('./load-env.cjs')
const Database = require('better-sqlite3')
const path = require('node:path')
const fs = require('node:fs')
const crypto = require('node:crypto')
const { drizzle } = require('drizzle-orm/better-sqlite3')
const { migrate } = require('drizzle-orm/better-sqlite3/migrator')
const { register } = require('./seed-work-scope.cjs')
async function main() {
  const file = path.resolve(process.env.DATABASE_PATH || './data/estmanday.db')
  const db = new Database(file, { fileMustExist: true })
  db.pragma('foreign_keys = ON')
  const signature = () => crypto.createHash('sha256').update(JSON.stringify(db.prepare('SELECT * FROM project_item_mandays ORDER BY id').all())).digest('hex')
  const before = signature()
  const backupDir = path.join(path.dirname(file), 'backups')
  fs.mkdirSync(backupDir, { recursive: true })
  const backup = path.join(backupDir, `before-work-scope-${Date.now()}.db`)
  await db.backup(backup)
  migrate(drizzle(db), { migrationsFolder: './drizzle' })
  register(db)
  if (before !== signature()) throw new Error(`Project MD changed; backup: ${backup}`)
  console.log(`Scope upgrade complete. Project MD unchanged. Backup: ${backup}`)
  db.close()
}
main().catch(error => { console.error(error); process.exitCode = 1 })
